def get_article(article_id: str) -> dict[str, Any] | None:
    for item in KNOWLEDGE:
        if item["id"] == article_id:
            return dict(item)
    return get_source(article_id)


def search_knowledge(query: str) -> list[dict[str, Any]]:
    q = normalize(query)
    tokens = [t for t in re.split(r"[\s،,]+", q) if len(t) > 1]
    if not tokens:
        return []
    results: list[tuple[int, dict[str, Any]]] = []
    for item in KNOWLEDGE:
        hay = normalize(
            " ".join(
                [
                    item["title"],
                    item["content"],
                    item["source"],
                    " ".join(item["tags"]),
                ]
            )
        )
        score = sum(1 for t in tokens if t in hay)
        # عنوان مهمتر از بدنه
        title_hay = normalize(item["title"] + " " + " ".join(item["tags"]))
        score += sum(2 for t in tokens if t in title_hay)
        if score > 0:
            results.append((score, item))
    results.sort(key=lambda x: x[0], reverse=True)
    merged = [dict(item) for _, item in results]
    # منابع رسمی دانلودشده (FDA/NIH/... و منابع فارسی) هم جستجو می‌شوند
    merged.extend(search_sources(query))
    return merged[:MAX_RESULTS]
